const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sofa', {
  boot: () => ipcRenderer.invoke('boot'),
  rescan: () => ipcRenderer.invoke('rescan'),
  launch: (id) => ipcRenderer.invoke('launch', id),
  setItem: (id, patch) => ipcRenderer.invoke('item:set', id, patch),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  setupDone: () => ipcRenderer.invoke('setup:done'),
  setupReset: () => ipcRenderer.invoke('setup:reset'),
  open: (uri) => ipcRenderer.invoke('open', uri),
  pad: (cmd) => ipcRenderer.send('pad', cmd),
  onLibrary: (fn) => ipcRenderer.on('library', (_e, v) => fn(v)),
  onHome: (fn) => ipcRenderer.on('home', (_e, info) => fn(info)),
  onRunning: (fn) => ipcRenderer.on('running', (_e, list) => fn(list)),
  running: () => ipcRenderer.invoke('running:get'),
  pictures: () => ipcRenderer.invoke('covers:list'),
  discord: () => ipcRenderer.invoke('social:discord'),
  setDiscordApp: (id, secret) => ipcRenderer.invoke('social:discordApp', id, secret),
  discordForget: () => ipcRenderer.invoke('social:discordForget'),
  discordConfig: () => ipcRenderer.invoke('social:discordConfig'),
  discordRecent: () => ipcRenderer.invoke('social:recentVoice'),
  discordGuild: (id) => ipcRenderer.invoke('social:guild', id),
  discordJoin: (id) => ipcRenderer.invoke('social:join', id),
  discordVoice: (patch) => ipcRenderer.invoke('social:voice', patch),
  openSocial: (url) => ipcRenderer.invoke('social:open', url),
  onSocial: (fn) => ipcRenderer.on('social:changed', () => fn()),
  clipboard: () => ipcRenderer.invoke('clipboard:read'),
  audioDevices: () => ipcRenderer.invoke('audio:list'),
  setAudio: (id) => ipcRenderer.invoke('audio:set', id),
  micMute: (mode) => ipcRenderer.invoke('audio:mic', mode),
  browsers: () => ipcRenderer.invoke('browser:list'),
  installFirefox: () => ipcRenderer.invoke('browser:installFirefox'),
  uninstallCheck: (id) => ipcRenderer.invoke('uninstall:check', id),
  uninstall: (id) => ipcRenderer.invoke('uninstall:run', id),
  padHome: (kind) => ipcRenderer.send('pad:home', kind),
  setCover: (id, src) => ipcRenderer.invoke('covers:set', id, src),
  browseCover: (id) => ipcRenderer.invoke('covers:browse', id),
  resume: (hwnd) => ipcRenderer.invoke('running:resume', hwnd),
  closeRunning: (hwnd, force) => ipcRenderer.invoke('running:close', hwnd, !!force),
  desktop: () => ipcRenderer.invoke('desktop'),
  onSteamGrab: (fn) => ipcRenderer.on('steam:grab', () => fn()),
});
